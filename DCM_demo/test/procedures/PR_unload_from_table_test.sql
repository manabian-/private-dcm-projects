-- テスト用テーブルの作成
CREATE OR REPLACE TABLE ORDERS (
    ORDER_ID                  NUMBER,
    CUSTOMER_NAME             VARCHAR,
    AMOUNT                    NUMBER(18, 2),
    ORDER_DATE                DATE,
    AUDIT__INGEST_TIMESTAMP   TIMESTAMP_NTZ(9),
    AUDIT__UPDATA1_TIMESTAMP  TIMESTAMP_NTZ(9) NOT NULL,
    AUDIT__DELETE_FLG         BOOLEAN DEFAULT FALSE
);

