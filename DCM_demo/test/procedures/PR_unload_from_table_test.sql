    P_TARGET_STAGE     => 'UNLOAD_QUERY_CDC_TEST_DB.TEST_SCHEMA.ORDERS_CDC_STAGE',
    P_CHECKPOINT_STAGE => 'UNLOAD_QUERY_CDC_TEST_DB.TEST_SCHEMA.CHECKPOINT_STAGE',
    P_TARGET_PATH      => 'output/UNLOAD_QUERY_CDC_TEST_DB.TEST_SCHEMA.ORDERS',
    P_CHECKPOINT_PATH  => 'checkpoints/UNLOAD_QUERY_CDC_TEST_DB.TEST_SCHEMA.ORDERS',
    P_TIMESTAMP_COLUMN => 'AUDIT__UPDATE_TIMESTAMP',
    P_LOOKBACK_SECONDS => 0
);

