-- プロシージャの実行
CALL PROCEDURES.SP_UNLOAD_FROM_TABLE_v1(
    P_SOURCE_QUERY => $$
        SELECT
            ORDER_ID,
            CUSTOMER_NAME,
            AMOUNT,
            ORDER_DATE,
            AUDIT__INGEST_TIMESTAMP,
            AUDIT__UPDATE_TIMESTAMP,
            AUDIT__DELETE_FLG
