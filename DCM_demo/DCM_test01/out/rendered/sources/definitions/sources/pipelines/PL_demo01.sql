



















-- Orders の Bronze / Silver、Stream、Task Graph をこのファイルで管理する。
-- SQL ファイルの並び順はデプロイ順序ではない。

-- schema
DEFINE SCHEMA DCM_TEST01_DEV.PL_DEMO01;

-- Ingest:ソースファイルを配置するADLSパス
DEFINE STAGE DCM_TEST01_DEV.PL_DEMO01.SOURCE_STAGE
    URL = 'azure://adlszealast01.blob.core.windows.net/snowpipe-test/inbound/PL_demo01'
    STORAGE_INTEGRATION = SI_INBOUND;

-- output:unload出力先ADLSパス
DEFINE STAGE DCM_TEST01_DEV.PL_DEMO01.OUTPUT_STAGE
    URL = 'azure://adlszealast01.blob.core.windows.net/snowpipe-test/inbound/PL_demo01'
    STORAGE_INTEGRATION = SI_INBOUND;

-- databricks 起動用ファイル出力先ADLSパス
DEFINE STAGE DCM_TEST01_DEV.PL_DEMO01.JOB_TRIGGER_STAGE
    URL = 'azure://adlszealast01.blob.core.windows.net/snowpipe-test/inbound/databricks-trigger/'
    STORAGE_INTEGRATION = SI_INBOUND;

-- Bronze: 原文の文字列を保持し、COPY のメタデータを監査列に記録する。
DEFINE TABLE DCM_TEST01_DEV.PL_DEMO01.ORDERS_BRONZE (
    ORDER_ID VARCHAR,
    CUSTOMER_NAME VARCHAR,
    AMOUNT VARCHAR,
    ORDER_DATE VARCHAR,
    AUDIT__INGEST_TIMESTAMP TIMESTAMP_LTZ,
    AUDIT__UPDATE_TIMESTAMP TIMESTAMP_LTZ
);

-- Silver: 型を揃え、ORDER_ID ごとに最新のレコードを保持する。
DEFINE TABLE DCM_TEST01_DEV.PL_DEMO01.ORDERS (
    ORDER_ID NUMBER,
    CUSTOMER_NAME VARCHAR,
    AMOUNT NUMBER(18, 2),
    ORDER_DATE DATE,
    AUDIT__INGEST_TIMESTAMP TIMESTAMP_LTZ,
    AUDIT__UPDATE_TIMESTAMP TIMESTAMP_LTZ
)
    CHANGE_TRACKING = TRUE;

DEFINE STREAM DCM_TEST01_DEV.PL_DEMO01.ORDERS_STREAM
    ON TABLE DCM_TEST01_DEV.PL_DEMO01.ORDERS
    APPEND_ONLY = FALSE
    SHOW_INITIAL_ROWS = FALSE;

-- file moveは一旦削除

DEFINE TASK DCM_TEST01_DEV.PL_DEMO01.TASK_COPY_ORDERS
    WAREHOUSE = 'DCM_DEMO_WH'
    TIMEZONE = 'UTC', AUTOCOMMIT = TRUE
    -- 
    -- 
    SUSPENDED
AS
DECLARE
    copy_result VARCHAR;
    check_result VARCHAR;
BEGIN
    CALL DCM_TEST01_DEV.PROCEDURES.SP_COPY_v1(
        P_TARGET_TABLE => 'DCM_TEST01_DEV.PL_DEMO01.ORDERS_BRONZE',
        -- ファイル移動を行わないのでsource stageを読み取る
        P_SOURCE_STAGE => 'DCM_TEST01_DEV.PL_DEMO01.SOURCE_STAGE',
        P_SOURCE_PATH => 'source/',
        P_FILE_FORMAT => $$
            TYPE = CSV
            PARSE_HEADER = TRUE
            FIELD_OPTIONALLY_ENCLOSED_BY = '"'
            ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
        $$,
        P_MATCH_BY_COLUMN_NAME => 'CASE_INSENSITIVE',
        P_INCLUDE_METADATA => $$
            AUDIT__INGEST_TIMESTAMP = METADATA$FILE_LAST_MODIFIED,
            AUDIT__UPDATE_TIMESTAMP = METADATA$START_SCAN_TIME
        $$,
        P_ON_ERROR => 'SKIP_FILE',
        P_FORCE => FALSE,
        P_PURGE => FALSE
    ) INTO :copy_result;

    CALL SYSTEM$SET_RETURN_VALUE(:copy_result);

    -- ファイル単位の失敗と COPY SQL 自体の失敗のどちらも後続を停止する。
    CALL DCM_TEST01_DEV.PROCEDURES.SP_CHECK_COPY_RESULT_v1(
        :copy_result, TRUE, TRUE
    ) INTO :check_result;

END;

DEFINE TASK DCM_TEST01_DEV.PL_DEMO01.TASK_MERGE_ORDERS
    WAREHOUSE = 'DCM_DEMO_WH'
    TIMEZONE = 'UTC', AUTOCOMMIT = TRUE
    AFTER DCM_TEST01_DEV.PL_DEMO01.TASK_COPY_ORDERS
    STARTED
AS
DECLARE
    merge_result VARIANT;
    return_value VARCHAR;
BEGIN
    CALL DCM_TEST01_DEV.PROCEDURES.SP_UPSERT_BRONZE_TO_SILVER_v1(
        P_TARGET_TABLE => 'DCM_TEST01_DEV.PL_DEMO01.ORDERS',
        P_SOURCE_SQL => $$
            SELECT
                TRY_CAST(ORDER_ID AS NUMBER) AS ORDER_ID,
                CUSTOMER_NAME,
                TRY_CAST(AMOUNT AS NUMBER(18, 2)) AS AMOUNT,
                TRY_CAST(ORDER_DATE AS DATE) AS ORDER_DATE,
                AUDIT__INGEST_TIMESTAMP,
                AUDIT__UPDATE_TIMESTAMP
            FROM DCM_TEST01_DEV.PL_DEMO01.ORDERS_BRONZE
        $$,
        P_PRIMARY_KEYS => ARRAY_CONSTRUCT('ORDER_ID')
    ) INTO :merge_result;

    return_value := TO_JSON(:merge_result);


    CALL SYSTEM$SET_RETURN_VALUE(:return_value);
END;

DEFINE TASK DCM_TEST01_DEV.PL_DEMO01.TASK_CLEANUP_ORDERS_BRONZE
    WAREHOUSE = 'DCM_DEMO_WH'
    TIMEZONE = 'UTC', AUTOCOMMIT = TRUE
    AFTER DCM_TEST01_DEV.PL_DEMO01.TASK_MERGE_ORDERS
    STARTED
AS
DECLARE
    delete_result VARCHAR DEFAULT 'SKIPPED: retention_days <= 0';
BEGIN
    -- Silver の MERGE が成功した後に Bronze だけを削除する。
    IF (60 > 0) THEN
        CALL DCM_TEST01_DEV.PROCEDURES.SP_DELETE_OLD_ORDERS_v1(
            P_TARGET_TABLE => 'DCM_TEST01_DEV.PL_DEMO01.ORDERS_BRONZE',
            RETENTION_DAYS => 60
        ) INTO :delete_result;
    END IF;

    CALL SYSTEM$SET_RETURN_VALUE(:delete_result);
END;

DEFINE TASK DCM_TEST01_DEV.PL_DEMO01.TASK_UNLOAD_ORDERS_CDC
    WAREHOUSE = 'DCM_DEMO_WH'
    TIMEZONE = 'UTC', AUTOCOMMIT = TRUE
    AFTER DCM_TEST01_DEV.PL_DEMO01.TASK_CLEANUP_ORDERS_BRONZE
    WHEN SYSTEM$STREAM_HAS_DATA('DCM_TEST01_DEV.PL_DEMO01.ORDERS_STREAM')
    STARTED
AS
DECLARE
    unload_query_id VARCHAR;
BEGIN
    CALL DCM_TEST01_DEV.PROCEDURES.SP_UNLOAD_v1(
        P_TARGET_STAGE => 'DCM_TEST01_DEV.PL_DEMO01.OUTPUT_STAGE',
        P_TARGET_PATH => 'output/',
        P_SOURCE_QUERY => $$
            SELECT
                ORDER_ID,
                CUSTOMER_NAME,
                AMOUNT,
                ORDER_DATE,
                CONVERT_TIMEZONE('UTC', AUDIT__INGEST_TIMESTAMP)::TIMESTAMP_NTZ(0) AS AUDIT__INGEST_TIMESTAMP,
                CONVERT_TIMEZONE('UTC', AUDIT__UPDATE_TIMESTAMP)::TIMESTAMP_NTZ(0) AS AUDIT__UPDATE_TIMESTAMP,
                METADATA$ACTION AS AUDIT_METADATA_ACTION,
                METADATA$ISUPDATE AS AUDIT_METADATA_ISUPDATE,
                METADATA$ROW_ID AS AUDIT_METADATA_ROW_ID
            FROM DCM_TEST01_DEV.PL_DEMO01.ORDERS_STREAM
        $$,
        P_FILE_FORMAT => $$
            TYPE = PARQUET
            COMPRESSION = SNAPPY
        $$,
        P_PARTITION_BY => $$
            'audit__ingest_timestamp=' ||
            TO_VARCHAR(CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP()),
                       'YYYY-MM-DD"T"HH24:MI:SS"Z"')
        $$,
        P_MAX_FILE_SIZE => 268435456,
        P_INCLUDE_QUERY_ID => TRUE,
        P_DETAILED_OUTPUT => TRUE
    ) INTO :unload_query_id;

    CALL SYSTEM$SET_RETURN_VALUE(:unload_query_id);    
END;

DEFINE TASK DCM_TEST01_DEV.PL_DEMO01.TASK_PUT_DATABRICKS_TRIGGER
    WAREHOUSE = 'DCM_DEMO_WH'
    TIMEZONE = 'UTC', AUTOCOMMIT = TRUE
    AFTER DCM_TEST01_DEV.PL_DEMO01.TASK_UNLOAD_ORDERS_CDC
    STARTED
AS
DECLARE
    trigger_result VARIANT;
    return_value VARCHAR;
BEGIN

    CALL DCM_TEST01_DEV.PROCEDURES.SP_PUT_DATABRICKS_TRIGGER_V1(
        P_TARGET_STAGE => 'DCM_TEST01_DEV.PL_DEMO01.JOB_TRIGGER_STAGE',
        P_TARGET_PATH  => 'job_a'
    ) INTO :trigger_result;

    return_value := TO_JSON(:trigger_result);

    CALL SYSTEM$SET_RETURN_VALUE(:return_value);

END;